class Engine:
    def __init__(self):
        self.tt = {}
        self.history = {}
        self.killers = [[None, None] for _ in range(MAX_PLY + 2)]
        self.pst = build_pst(24)
        self.path = set()
        self.game_rep = set()
        self.nodes = 0
        self.deadline = 0.0
        self.contempt = 0
        self.eg_mode = False
        self.game_ply = 0
        self.root_best = None
        self.root_score = 0
        self.depth_done = 0
        self.root_bias = {}
        self.phase = 24
        self.pawn_cache = {}
        self.rook_open = ROOK_OPEN[0]
        self.rook_semi = ROOK_SEMI[0]
        self.shelter_w = SHELTER

    def new_game(self):
        self.tt.clear()
        self.history.clear()
        self.killers = [[None, None] for _ in range(MAX_PLY + 2)]

    # ------------------------------------------------------------ evaluation
    def evaluate(self, board, score):
        pk = board.translate(PAWN_TRANS)
        entry = self.pawn_cache.get(pk)
        if entry is None:
            mg, eg = pawn_terms(pk)
            ph = self.phase
            ps = (mg * ph + eg * (24 - ph)) // 24
            up_files = lo_files = 0
            for i in SQUARES:
                c = pk[i]
                if c == "P":
                    up_files |= 1 << (i % 10)
                elif c == "p":
                    lo_files |= 1 << (i % 10)
            entry = (ps, up_files, lo_files)
            self.pawn_cache[pk] = entry
        ps, up_files, lo_files = entry
        s = score + 10 + ps
        # Rooks on open (no pawns) or half-open (no own pawns) files.
        i = board.find("R")
        while i != -1:
            bit = 1 << (i % 10)
            if not up_files & bit:
                s += self.rook_semi if lo_files & bit else self.rook_open
            i = board.find("R", i + 1)
        i = board.find("r")
        while i != -1:
            bit = 1 << (i % 10)
            if not lo_files & bit:
                s -= self.rook_semi if up_files & bit else self.rook_open
            i = board.find("r", i + 1)
        # King shelter: own pawns in front of a castled king (middlegame).
        if self.shelter_w:
            k = board.find("K")
            if k > 80 and k % 10 not in (4, 5):
                sh = 2 * ((board[k - 11] == "P") + (board[k - 10] == "P") + (board[k - 9] == "P")) + (
                    (board[k - 21] == "P") + (board[k - 20] == "P") + (board[k - 19] == "P"))
                s += sh * self.shelter_w
            k = board.find("k")
            if k < 40 and k % 10 not in (4, 5):
                sh = 2 * ((board[k + 9] == "p") + (board[k + 10] == "p") + (board[k + 11] == "p")) + (
                    (board[k + 19] == "p") + (board[k + 20] == "p") + (board[k + 21] == "p"))
                s -= sh * self.shelter_w
        if board.count("B") >= 2:
            s += 30
        if board.count("b") >= 2:
            s -= 30
        if self.eg_mode:
            s = self.endgame_terms(board, s)
        return s

    def endgame_terms(self, board, s):
        cnt = board.count
        up_p, lo_p = cnt("P"), cnt("p")
        up_m = 3 * (cnt("N") + cnt("B")) + 5 * cnt("R") + 9 * cnt("Q")
        lo_m = 3 * (cnt("n") + cnt("b")) + 5 * cnt("r") + 9 * cnt("q")
        if up_p == 0 and lo_p == 0:
            if up_m <= 3 and lo_m <= 3:
                return 0
            if (up_m == 6 and lo_m == 0 and cnt("N") == 2) or (lo_m == 6 and up_m == 0 and cnt("n") == 2):
                return s // 16
            if abs(up_m - lo_m) <= 3:
                s //= 4
        elif s > 0 and up_p == 0 and up_m - lo_m <= 3:
            s //= 2
        elif s < 0 and lo_p == 0 and lo_m - up_m <= 3:
            s //= 2
        # Mop-up: drive a bare king to the edge and bring our king closer.
        if lo_m == 0 and up_m >= 5:
            wk, lk = board.find("K"), board.find("k")
            dist = abs(RANK_OF[wk] - RANK_OF[lk]) + abs(FILE_OF[wk] - FILE_OF[lk])
            s += 10 * CMD[lk] + 4 * (14 - dist)
        elif up_m == 0 and lo_m >= 5:
            wk, lk = board.find("k"), board.find("K")
            dist = abs(RANK_OF[wk] - RANK_OF[lk]) + abs(FILE_OF[wk] - FILE_OF[lk])
            s -= 10 * CMD[lk] + 4 * (14 - dist)
        return s

    def draw_score(self, ply):
        return -self.contempt if ply % 2 == 0 else self.contempt

    # ------------------------------------------------------------ quiescence
    def qsearch(self, pos, alpha, beta, ply):
        self.nodes += 1
        if not self.nodes & 1023 and time.perf_counter() > self.deadline:
            raise TimeUp
        board = pos[0]
        k = board.find("K")
        in_check = attacked(board, k)
        pst = self.pst
        ep = pos[3]
        if in_check:
            if ply >= MAX_PLY:
                return self.evaluate(board, pos[4])
            best = -MATE + ply
            line_k = LINE[k]
            for m in gen_moves(board, pos[1], ep, k, True):
                child = make_move(pos, m, k, True, pst)
                if child is None:
                    continue
                score = -self.qsearch(child, -beta, -alpha, ply + 1)
                if score > best:
                    best = score
                    if score > alpha:
                        alpha = score
                        if score >= beta:
                            break
            return best
        stand = self.evaluate(board, pos[4])
        if stand >= beta or ply >= MAX_PLY:
            return stand
        if stand > alpha:
            alpha = stand
        caps = gen_captures(board, ep)
        if not caps:
            return stand
        line_k = LINE[k]
        scored = []
        for m in caps:
            i, j, pr = m
            q = board[j]
            p = board[i]
            gain = MVV.get(q, 100)
            if pr:
                gain += 800
            elif stand + gain + 200 < alpha:
                continue  # delta pruning
            if PIECE_VAL[p] > gain + 50 and (board[j - 11] == "p" or board[j - 9] == "p"):
                continue  # pawn-defended target, capture likely loses material
            scored.append((gain * 10 - LVA[p], m))
        scored.sort(reverse=True)
        best = stand
        for _, m in scored:
            i = m[0]
            need = board[i] == "K" or i in line_k or (m[1] == ep and board[i] == "P")
            child = make_move(pos, m, k, need, pst)
            if child is None:
                continue
            score = -self.qsearch(child, -beta, -alpha, ply + 1)
            if score > best:
                best = score
                if score > alpha:
                    alpha = score
                    if score >= beta:
                        break
        return best

    # ------------------------------------------------------------ main search
    def search(self, pos, depth, alpha, beta, ply, hm, can_null):
        self.nodes += 1
        if not self.nodes & 1023 and time.perf_counter() > self.deadline:
            raise TimeUp
        board = pos[0]
        key = pos[:4]
        pv_node = beta - alpha > 1
        if ply:
            if hm >= 100 or key in self.path or key in self.game_rep or self.game_ply + ply >= 500:
                return self.draw_score(ply)
            # mate distance pruning
            if alpha < -MATE + ply:
                alpha = -MATE + ply
            if beta > MATE - ply - 1:
                beta = MATE - ply - 1
            if alpha >= beta:
                return alpha
        k = board.find("K")
        in_check = attacked(board, k)
        if in_check and ply < MAX_PLY:
            depth += 1
        if depth <= 0:
            return self.qsearch(pos, alpha, beta, ply)
        if ply >= MAX_PLY:
            return self.evaluate(board, pos[4])

        tt = self.tt
        entry = tt.get(key)
        tt_move = None
        if entry is not None:
            e_depth, e_flag, e_score, tt_move = entry
            if e_depth >= depth and not pv_node and ply:
                if e_score > MATE_BOUND:
                    e_score -= ply
                elif e_score < -MATE_BOUND:
                    e_score += ply
                if e_flag == EXACT or (e_flag == LOWER and e_score >= beta) or (e_flag == UPPER and e_score <= alpha):
                    return e_score

        if in_check:
            static = -INF
        else:
            static = self.evaluate(board, pos[4])
            if not pv_node:
                # reverse futility pruning
                if depth <= 3 and static - 110 * depth >= beta and beta > -MATE_BOUND and beta < MATE_BOUND:
                    return static
                # null-move pruning
                if can_null and depth >= 3 and static >= beta and (
                    "Q" in board or "R" in board or "B" in board or "N" in board
                ):
                    r = 3 if depth >= 7 else 2
                    null = (board[::-1].swapcase(), pos[2], pos[1], 0, -pos[4])
                    self.path.add(key)
                    try:
                        score = -self.search(null, depth - 1 - r, -beta, -beta + 1, ply + 1, hm + 1, False)
                    finally:
                        self.path.discard(key)
                    if score >= beta:
                        return beta if score >= MATE_BOUND else score

        futile = (not pv_node and not in_check and depth <= 2
                  and static + (120 if depth == 1 else 320) <= alpha)

        pst = self.pst
        ep = pos[3]
        line_k = LINE[k]
        killers = self.killers[ply]
        history = self.history
        orig_alpha = alpha
        best = -INF
        best_move = None
        searched = 0
        generated = False
        moves = [tt_move] if tt_move is not None else None
        if moves is None:
            moves = self.ordered_moves(board, pos[1], ep, k, in_check, None, killers)
            generated = True
        idx = 0
        self.path.add(key)
        try:
            while True:
                if idx >= len(moves):
                    if generated:
                        break
                    moves = self.ordered_moves(board, pos[1], ep, k, in_check, tt_move, killers)
                    generated = True
                    idx = 0
                    continue
                m = moves[idx]
                idx += 1
                i, j, pr = m
                p = board[i]
                q = board[j]
                capture = q != "." or (p == "P" and j == ep)
                quiet = not capture and not pr
                need = in_check or p == "K" or i in line_k or (p == "P" and j == ep)
                child = make_move(pos, m, k, need, pst)
                if child is None:
                    continue
                if futile and quiet and searched and not attacked(child[0], child[0].find("K")):
                    continue
                new_hm = 0 if (capture or p == "P") else hm + 1
                if not ply and self.root_bias:
                    # Series memory: bias this root move, searching with a
                    # shifted window so the biased score is still exact.
                    b = self.root_bias.get(m, 0)
                    a0, b0 = alpha - b, beta - b
                    score = -self.search(child, depth - 1, -b0, -a0, ply + 1, new_hm, True) + b
                elif searched == 0:
                    score = -self.search(child, depth - 1, -beta, -alpha, ply + 1, new_hm, True)
                else:
                    r = 0
                    if depth >= 3 and searched >= 3 and quiet and not in_check and m != killers[0] and m != killers[1]:
                        r = LMR[min(depth, 63)][min(searched, 63)]
                        if pv_node and r:
                            r -= 1
                        if r > depth - 2:
                            r = depth - 2
                        if r < 0:
                            r = 0
                    score = -self.search(child, depth - 1 - r, -alpha - 1, -alpha, ply + 1, new_hm, True)
                    if r and score > alpha:
                        score = -self.search(child, depth - 1, -alpha - 1, -alpha, ply + 1, new_hm, True)
                    if alpha < score < beta:
                        score = -self.search(child, depth - 1, -beta, -alpha, ply + 1, new_hm, True)
                searched += 1
                if score > best:
                    best = score
                    best_move = m
                    if score > alpha:
                        alpha = score
                        if ply == 0:
                            self.root_best = m
                            self.root_score = score
                        if score >= beta:
                            if quiet:
                                if killers[0] != m:
                                    killers[1] = killers[0]
                                    killers[0] = m
                                hkey = (p, j)
                                history[hkey] = history.get(hkey, 0) + depth * depth
                            break
        finally:
            self.path.discard(key)

        if searched == 0:
            return -MATE + ply if in_check else self.draw_score(ply)

        if best <= orig_alpha:
            flag = UPPER
        elif best >= beta:
            flag = LOWER
        else:
            flag = EXACT
        stored = best
        if stored > MATE_BOUND:
            stored += ply
        elif stored < -MATE_BOUND:
            stored -= ply
        tt[key] = (0 if (not ply and self.root_bias) else depth, flag, stored, best_move)
        return best

    def ordered_moves(self, board, wc, ep, k, in_check, skip, killers):
        history = self.history
        k0, k1 = killers
        scored = []
        add = scored.append
        for m in gen_moves(board, wc, ep, k, in_check):
            if m == skip:
                continue
            i, j, pr = m
            q = board[j]
            p = board[i]
            if q != ".":
                v = MVV[q]
                if PIECE_VAL[p] > v + 50 and (board[j - 11] == "p" or board[j - 9] == "p"):
                    sc = 700000 + v * 10 - LVA[p]
                else:
                    sc = 1000000 + v * 10 - LVA[p]
            elif pr == "Q":
                sc = 950000
            elif p == "P" and j == ep:
                sc = 1000000 + 999
            elif m == k0:
                sc = 900000
            elif m == k1:
                sc = 890000
            elif pr:
                sc = -1
            else:
                sc = history.get((p, j), 0)
            add((sc, m))
        scored.sort(reverse=True)
        return [m for _, m in scored]

    # ------------------------------------------------------------ driver
    def think(self, cb, game_keys, game_ply, soft, hard, contempt, bias=None):
        """Iterative deepening. Returns (uci, score, depth, nodes)."""
        phase = 0
        for piece in cb.piece_map().values():
            phase += PHASE_W[piece.symbol().upper()]
        phase = min(phase, 24)
        self.pst = build_pst(phase)
        self.eg_mode = phase <= 12
        if phase != self.phase or len(self.pawn_cache) > 100_000:
            self.pawn_cache = {}
        self.phase = phase
        self.rook_open = (ROOK_OPEN[0] * phase + ROOK_OPEN[1] * (24 - phase)) // 24
        self.rook_semi = (ROOK_SEMI[0] * phase + ROOK_SEMI[1] * (24 - phase)) // 24
        self.shelter_w = SHELTER * phase // 24
        self.contempt = contempt
        self.game_ply = game_ply
        root = pos_from_chess(cb, self.pst)
        white = cb.turn == chess.WHITE
        self.root_bias = {}
        if bias:
            rb = root[0]
            rk = rb.find("K")
            for m in gen_moves(rb, root[1], root[3], rk, attacked(rb, rk)):
                b = bias.get(move_to_uci(m, white))
                if b:
                    self.root_bias[m] = b

        # Positions seen at least twice before the root: reaching one again
        # would be a threefold repetition, which the referee claims.
        counts = {}
        for key in game_keys:
            counts[key] = counts.get(key, 0) + 1
        self.game_rep = set()
        for key, c in counts.items():
            if c >= 2:
                try:
                    self.game_rep.add(pos_from_chess(chess.Board(key + " 0 1"), self.pst)[:4])
                except ValueError:
                    pass
        self.path = set()

        if len(self.tt) > TT_LIMIT:
            self.tt.clear()
        for key in list(self.history):
            self.history[key] >>= 2
        self.killers = [[None, None] for _ in range(MAX_PLY + 2)]

        start = time.perf_counter()
        self.deadline = start + hard
        self.nodes = 0
        self.root_best = None
        best_move = None
        best_score = 0
        depth_done = 0
        hm = cb.halfmove_clock
        score = 0
        try:
            for depth in range(1, MAX_PLY):
                if depth >= 4:
                    window = 35
                    alpha, beta = score - window, score + window
                    while True:
                        score = self.search(root, depth, alpha, beta, 0, hm, True)
                        if score <= alpha:
                            alpha = max(-INF, alpha - window * 3)
                            window *= 3
                        elif score >= beta:
                            beta = min(INF, beta + window * 3)
                            window *= 3
                        else:
                            break
                        if window > 1000:
                            alpha, beta = -INF, INF
                else:
                    score = self.search(root, depth, -INF, INF, 0, hm, True)
                best_move = self.root_best
                best_score = score
                depth_done = depth
                elapsed = time.perf_counter() - start
                if elapsed > soft * 0.5:
                    break
                if abs(score) > MATE_BOUND and depth >= 2 * (MATE - abs(score)) + 2:
                    break
        except TimeUp:
            if self.root_best is not None:
                best_move = self.root_best
        self.depth_done = depth_done
        if best_move is None:
            return None, 0, 0, self.nodes
        return move_to_uci(best_move, white), best_score, depth_done, self.nodes



# ---------------------------------------------------------------------------
# Evaluation tables: designed by hand from basic chess principles and
# generated by the formulas below (no values fitted to game data).
#   ring  = distance ring from the four centre squares (0 = centre, 3 = edge)
#   fedge = distance of the file from the centre files (0 = d/e, 3 = a/h)
#   rank  = 1..8 from the owner's side
# Tables are file-symmetric because the board representation rotates by
# 180 degrees. Values are centipawns; "mg" = middlegame, "eg" = endgame.
# ---------------------------------------------------------------------------
MG_VAL = {"P": 100, "N": 320, "B": 330, "R": 480, "Q": 950, "K": 0}
EG_VAL = {"P": 120, "N": 290, "B": 320, "R": 520, "Q": 950, "K": 0}
PHASE_W = {"P": 0, "N": 1, "B": 1, "R": 2, "Q": 4, "K": 0}


def _square_terms(piece, f, rank):
    """Hand-designed (mg, eg) positional bonus for a piece on file f, rank."""
    fedge = max(3 - f, f - 4)
    rdist = max(4 - rank, rank - 5)
    ring = max(fedge, rdist)
    if piece == "P":
        # advance in the endgame; occupy the centre in the middlegame;
        # keep wing pawns home as king shelter.
        mg = {2: 0, 3: 5, 4: 10, 5: 20, 6: 35, 7: 60}.get(rank, 0)
        if fedge == 0:
            mg += {2: -15, 4: 20, 5: 25, 6: 20}.get(rank, 0)
        elif fedge == 1:
            mg += {4: 5, 5: 10}.get(rank, 0)
        elif rank == 2:
            mg += 5
        eg = {3: 10, 4: 20, 5: 40, 6: 70, 7: 110}.get(rank, 0)
        return mg, eg
    if piece == "N":
        # knights are poor on the rim, good in the centre and on outposts
        mg = (20, 10, -5, -30)[ring]
        if rank in (5, 6) and fedge <= 2:
            mg += 10
        if rank == 1:
            mg -= 10  # develop
        return mg, (15, 10, -5, -25)[ring]
    if piece == "B":
        mg = (15, 10, 0, -10)[ring]
        if rank == 1:
            mg -= 10  # develop
        if f == rank - 1 or f == 8 - rank:
            mg += 10  # long diagonals
        return mg, (10, 5, 0, -10)[ring]
    if piece == "R":
        mg = 20 if rank == 7 else 0
        if rank == 1 and fedge <= 1:
            mg += 5  # central files after castling
        return mg, (15 if rank == 7 else 0)
    if piece == "Q":
        return (5, 5, 0, -10)[ring], (20, 10, 0, -15)[ring]
    # King: hide behind the pawns in the middlegame, centralise in the endgame.
    if rank == 1:
        mg = (-5, 5, 25, 15)[fedge]
    elif rank == 2:
        mg = (-20, -10, 5, 5)[fedge]
    else:
        mg = -30 - 15 * (rank - 3)
    eg = (30, 15, 0, -20)[ring]
    if fedge == 3 and rdist == 3:
        eg -= 10  # corners
    return mg, eg


MG_T = {}
EG_T = {}
for _p in "PNBRQK":
    _mg, _eg = [], []
    for _row in range(8):  # row 0 = rank 8 (same layout as a printed board)
        for _f in range(8):
            _m, _e = _square_terms(_p, _f, 8 - _row)
            _mg.append(_m)
            _eg.append(_e)
    MG_T[_p] = tuple(_mg)
    EG_T[_p] = tuple(_eg)

_PST_CACHE = {}

# Pawn structure: (mg, eg) bonuses by relative rank for passed pawns, and
# penalties for doubled / isolated pawns. Cached by the pawn-only board.
PASSED_MG = (0, 0, 0, 5, 10, 20, 35, 50, 0, 0)
PASSED_EG = (0, 0, 5, 10, 25, 45, 75, 110, 0, 0)
DOUBLED = (-10, -20)
ROOK_OPEN = (25, 10)  # rook on a file with no pawns (mg, eg)
ROOK_SEMI = (12, 5)  # rook on a file with no own pawns
SHELTER = 8  # per shelter point: pawn directly in front = 2, one further = 1
ISOLATED = (-8, -12)
PAWN_TRANS = str.maketrans({c: "." for c in "NBRQKnbrqk"})


def pawn_terms(pk):
    """Pawn-structure score (mg, eg) from the uppercase side's view."""
    up = [i for i in SQUARES if pk[i] == "P"]
    lo = [i for i in SQUARES if pk[i] == "p"]
    fu = [0] * 10
    fl = [0] * 10
    for i in up:
        fu[i % 10] += 1
    for i in lo:
        fl[i % 10] += 1
    mg = eg = 0
    for i in up:
        f, row = i % 10, i // 10
        passed = True
        for x in lo:
            if x // 10 < row and -1 <= x % 10 - f <= 1:
                passed = False
                break
        if passed:
            rank = 10 - row
            mg += PASSED_MG[rank]
            eg += PASSED_EG[rank]
        if fu[f - 1] == 0 and fu[f + 1] == 0:
            mg += ISOLATED[0]
            eg += ISOLATED[1]
    for i in lo:
        f, row = i % 10, i // 10
        passed = True
        for x in up:
            if x // 10 > row and -1 <= x % 10 - f <= 1:
                passed = False
                break
        if passed:
            rank = row - 1
            mg -= PASSED_MG[rank]
            eg -= PASSED_EG[rank]
        if fl[f - 1] == 0 and fl[f + 1] == 0:
            mg -= ISOLATED[0]
            eg -= ISOLATED[1]
    for f in range(1, 9):
        if fu[f] > 1:
            mg += DOUBLED[0] * (fu[f] - 1)
            eg += DOUBLED[1] * (fu[f] - 1)
        if fl[f] > 1:
            mg -= DOUBLED[0] * (fl[f] - 1)
            eg -= DOUBLED[1] * (fl[f] - 1)
    return mg, eg






def build_pst(phase):
    """Piece-square tables (material included) blended for a game phase 0..24."""
    phase = max(0, min(24, phase))
    cached = _PST_CACHE.get(phase)
    if cached is not None:
        return cached
    pst = {}
    for p in "PNBRQK":
        tab = [0] * 120
        for r in range(8):
            for f in range(8):
                mg = (MG_T[p][r * 8 + f] + MG_T[p][r * 8 + 7 - f]) / 2 + MG_VAL[p]
                eg = (EG_T[p][r * 8 + f] + EG_T[p][r * 8 + 7 - f]) / 2 + EG_VAL[p]
                tab[21 + r * 10 + f] = int(round((mg * phase + eg * (24 - phase)) / 24))
        pst[p] = tab
    _PST_CACHE[phase] = pst
    return pst



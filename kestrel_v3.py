# Agent
# ---------------------------------------------------------------------------
SERIES_BIAS = 35  # centipawns: how far series memory may favour a winning line
SERIES_AVOID = 60  # centipawns: penalty on the move that lost an earlier game
MISTAKE_SWING = 60  # evaluation jump that marks a move as the losing mistake

FALLBACK_VAL = {chess.PAWN: 1, chess.KNIGHT: 3, chess.BISHOP: 3, chess.ROOK: 5, chess.QUEEN: 9, chess.KING: 0}


class KestrelAgent(ChessAgent):
    name = "Kestrel"

    def __init__(self):
        self.engine = Engine()
        self.record = {}
        self.games = {}
        self.cur_evals = {}
        self.history_keys = []
        self.last_index = None
        self.last_len = -1
        self.contempt = 15
        self.last_info = None
        self.last_bias = None

    def initialize(self, *, color, opponent_id, time_control, seed):
        self._new_game()
        self.contempt = self._base_contempt(opponent_id, 1)

    def _new_game(self):
        self.engine.new_game()
        self.cur_evals = {}
        self.history_keys = []
        self.last_len = -1

    def _base_contempt(self, opponent_id, game_index):
        """Draw valuation from what this series has shown so far.

        Early in a series the results estimate relative strength: play for
        wins against an opponent we have beaten, accept draws against one
        that beat us (expected points). From game 3 on, the series score
        itself matters, because knockout series are decided on it and ties
        go to the higher seed: when behind we need wins, when ahead a draw
        protects the lead.
        """
        w, d, l = self.record.get(opponent_id, (0, 0, 0))
        if w > l:
            c = 35  # we have beaten this opponent: play for wins
        elif l > w:
            c = -10  # opponent looks stronger: a draw is a fine result
        else:
            c = 15
        if game_index >= 3:
            if w < l:
                c += 40
            elif w > l:
                c -= 20
        return c

    def _series_bias(self, board, obs):
        """Root-move bias from earlier games of this matchup.

        Games in a series share starting positions (colors reversed in the
        league, possibly repeated in knockout pairs). If the current game
        has followed an earlier game move for move, we know what the side to
        move played there and how it ended for that side: reuse moves that
        won for it, steer away from moves that lost for it. The search still
        decides; the bias only shifts a move by SERIES_BIAS centipawns.
        """
        games = self.games.get(obs.opponent_id)
        if not games:
            return None
        n = len(obs.move_history)
        hist = tuple(obs.move_history)
        cur = fen_key(board.fen())
        white = board.turn == chess.WHITE
        bias = {}
        for moves, fens, white_result, evals, we_were_white in games:
            if len(moves) <= n or fens[n] != cur or moves[:n] != hist:
                continue
            side_result = white_result if white else 1.0 - white_result
            m = moves[n]
            if side_result == 1.0:
                # this side won that game: reuse its move
                bias[m] = min(bias.get(m, 0) + SERIES_BIAS, SERIES_BIAS)
            elif side_result == 0.0:
                # this side lost: deviate only where that game's evaluations
                # show the losing move was the mistake (our scores were
                # recorded after each of our own moves, from our side).
                if we_were_white != white:
                    before, after = evals.get(n - 1), evals.get(n + 1)
                    mistake = before is not None and after is not None and after - before >= MISTAKE_SWING
                else:
                    now, later = evals.get(n), evals.get(n + 2)
                    mistake = now is not None and later is not None and later - now <= -MISTAKE_SWING
                if mistake:
                    bias[m] = max(bias.get(m, 0) - SERIES_AVOID, -SERIES_AVOID)
        return {m: b for m, b in bias.items() if b} or None

    def on_game_end(self, result):
        try:
            if len(result.moves) <= 600:
                b = chess.Board(result.starting_fen)
                fens = [fen_key(b.fen())]
                for u in result.moves:
                    b.push_uci(u)
                    fens.append(fen_key(b.fen()))
                if result.my_color == "white":
                    white_result = result.my_score
                else:
                    white_result = result.opponent_score
                if result.termination_code in ("checkmate", "stalemate", "insufficient_material",
                                               "threefold_repetition", "fifty_moves", "fivefold_repetition",
                                               "seventyfive_moves", "maximum_plies"):
                    self.games.setdefault(result.opponent_id, []).append(
                        (tuple(result.moves), fens, float(white_result), dict(self.cur_evals),
                         result.my_color == "white"))
        except Exception:
            pass
        try:
            w, d, l = self.record.get(result.opponent_id, (0, 0, 0))
            if result.outcome == "win":
                w += 1
            elif result.outcome == "loss":
                l += 1
            else:
                d += 1
            self.record[result.opponent_id] = (w, d, l)
        except Exception:
            pass

    def choose_move(self, observation):
        try:
            board = chess.Board(observation.fen)
        except Exception:
            return "0000"
        try:
            return self._choose(board, observation)
        except Exception:
            return self._fallback(board)

    def _choose(self, board, obs):
        start = time.perf_counter()
        n_hist = len(obs.move_history)
        if n_hist < self.last_len or (self.last_index is not None and obs.match_game_index != self.last_index):
            self._new_game()
            self.contempt = self._base_contempt(obs.opponent_id, obs.match_game_index)
        self.last_index = obs.match_game_index
        self.last_len = n_hist

        legal = list(board.legal_moves)
        if len(legal) == 1:
            uci = legal[0].uci()
            self._remember(board, legal[0])
            return uci

        # Repetition history since the last irreversible move.
        root_key = fen_key(board.fen())
        self.history_keys.append(root_key)
        hm = board.halfmove_clock
        keys = self.history_keys[-(hm + 1):]

        # Time allocation.
        remaining = max(0.0, obs.my_remaining_time)
        inc = max(0.0, obs.increment)
        overhead = 0.05
        usable = max(0.0, remaining - overhead)
        soft = usable / 28.0 + inc * 0.8
        hard = min(soft * 2.2, usable * 0.25 + inc * 0.5, 4.0)
        soft = min(soft, hard)
        if remaining < 1.0:
            soft = min(soft, usable * 0.15)
            hard = min(hard, usable * 0.25)
        soft = max(soft, 0.01)
        hard = max(hard, 0.02)

        contempt = self._base_contempt(obs.opponent_id, obs.match_game_index)
        opp_time = obs.opponent_remaining_time
        if opp_time < 5.0 and remaining > 2.0 * opp_time:
            contempt += 25  # opponent in time trouble: keep the game going

        spent = time.perf_counter() - start
        bias = self._series_bias(board, obs)
        self.last_bias = bias
        uci, score, depth, nodes = self.engine.think(
            board, keys, n_hist, max(0.01, soft - spent), max(0.02, hard - spent), contempt, bias
        )
        self.last_info = (score, depth, nodes, time.perf_counter() - start)
        if uci is not None and abs(score) < MATE_BOUND + 1000:
            self.cur_evals[n_hist] = max(-3000, min(3000, score))
        move = None
        if uci is not None:
            try:
                move = chess.Move.from_uci(uci)
            except ValueError:
                move = None
        if move is None or move not in board.legal_moves:
            return self._fallback(board)
        self._remember(board, move)
        return move.uci()

    def _remember(self, board, move):
        try:
            if not self.history_keys or self.history_keys[-1] != fen_key(board.fen()):
                self.history_keys.append(fen_key(board.fen()))
            board.push(move)
            self.history_keys.append(fen_key(board.fen()))
            board.pop()
        except Exception:
            pass

    def _fallback(self, board):
        try:
            best = None
            best_v = -1
            for mv in board.legal_moves:
                v = 0
                victim = board.piece_type_at(mv.to_square)
                if victim:
                    v = 10 * FALLBACK_VAL[victim] - FALLBACK_VAL[board.piece_type_at(mv.from_square)]
                if mv.promotion == chess.QUEEN:
                    v += 80
                if v > best_v:
                    best_v = v
                    best = mv
            if best is not None:
                return best.uci()
        except Exception:
            pass
        for mv in board.legal_moves:
            return mv.uci()
        return "0000"

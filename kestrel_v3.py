"""Kestrel: a resource-bounded chess agent for the Chess Agent Competition.

Architecture (summary for the report)
-------------------------------------
* Board: own 10x12 "mailbox" stored as a 120-character string. The board is
  rotated 180 degrees after every move, so the side to move is always
  uppercase and always moves "up". String slicing, reversal and swapcase run
  in C, which makes move making much faster than python-chess push/pop.
  The rotated-string representation is an idea borrowed from Sunfish by
  Thomas Ahle (https://github.com/thomasahle/sunfish); this file is an
  independent implementation of that idea.
* Move generation is fully legal: a cheap pin/check filter only runs the
  attack test for moves that could possibly expose the king.
* Search: iterative deepening, principal-variation alpha-beta with aspiration
  windows, transposition table, null-move pruning, late-move reductions,
  reverse-futility and futility pruning, check extension, killer and history
  move ordering, and quiescence search with check evasions, delta pruning
  and a pawn-defended bad-capture filter.
* Evaluation: material and piece-square tables designed by hand from basic
  chess principles (centralisation, development, king shelter, pawn
  advancement, rooks on the 7th) and generated from explicit formulas;
  middlegame/endgame values are tapered by the game phase at the root;
  bishop pair; pawn structure (passed, doubled and isolated pawns, cached
  by pawn configuration); rooks on open and half-open files; pawn shelter
  in front of a castled king; endgame knowledge (mop-up to convert won
  endings, insufficient material and drawish-ending scaling). All values
  were chosen by hand; none is fitted to game data or engine output.
* Game-level logic: repetition-aware search using the real game history
  (the FEN in the observation carries no history), fifty-move and 500-ply
  awareness, contempt adapted from results earlier in the same matchup and
  from the opponent's clock, and a time manager with soft and hard limits.
* Series memory: games in a series share starting positions (colors are
  reversed within each pair). After every game the agent stores the moves,
  the result and its own evaluation after each of its moves. When a later
  game retraces an earlier one move for move, the agent favours the moves
  that won for the side it is now playing ("strategy stealing"), and steers
  away from the single move where its stored evaluations show the losing
  side went wrong. That also defends against opponents who copy our winning
  lines. The search still decides; memory only shifts a root move's score.
  All learned state lives in the agent instance (nothing is written to
  disk), so it resets with the fresh instance created for each matchup.
* Series-aware draw valuation: from game 3 of a series, the draw value
  follows the series score (behind: play for wins; ahead: a draw protects
  the lead), because knockout series are decided on series score and ties
  go to the higher seed.
* Reliability: every move is verified with python-chess before it is
  returned, and any internal failure falls back to a safe legal move.
"""


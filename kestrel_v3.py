# Precomputed target squares and rays (on-board squares only), so the inner
# loops iterate over tuples instead of doing index arithmetic.
def _ray(i, d):
    out = []
    j = i + d
    while j in SQSET:
        out.append(j)
        j += d
    return tuple(out)


KNIGHT_TGT = [()] * 120
KING_TGT = [()] * 120
ORTH_RAYS = [()] * 120
DIAG_RAYS = [()] * 120
QUEEN_RAYS = [()] * 120
for _i in SQUARES:
    KNIGHT_TGT[_i] = tuple(_i + d for d in KNIGHT_D if _i + d in SQSET)
    KING_TGT[_i] = tuple(_i + d for d in KING_D if _i + d in SQSET)
    ORTH_RAYS[_i] = tuple(r for r in (_ray(_i, d) for d in ORTH) if r)
    DIAG_RAYS[_i] = tuple(r for r in (_ray(_i, d) for d in DIAG) if r)
    QUEEN_RAYS[_i] = ORTH_RAYS[_i] + DIAG_RAYS[_i]
SLIDER_RAYS = {"B": DIAG_RAYS, "R": ORTH_RAYS, "Q": QUEEN_RAYS}
ENEMY = "pnbrq"
EMPTY_OR_ENEMY = ".pnbrq"


def attacked(board, s):
    """True if square s is attacked by the side NOT to move (lowercase)."""
    if board[s - 11] == "p" or board[s - 9] == "p":
        return True
    for j in KNIGHT_TGT[s]:
        if board[j] == "n":
            return True
    for j in KING_TGT[s]:
        if board[j] == "k":
            return True
    for ray in ORTH_RAYS[s]:
        for j in ray:
            q = board[j]
            if q != ".":
                if q == "r" or q == "q":
                    return True
                break
    for ray in DIAG_RAYS[s]:
        for j in ray:
            q = board[j]
            if q != ".":
                if q == "b" or q == "q":
                    return True
                break
    return False


def gen_moves(board, wc, ep, k, in_check):
    """Pseudo-legal moves (plus castling that is already check-safe)."""
    moves = []
    add = moves.append
    for mo in OWN_RE.finditer(board):
        i = mo.start()
        p = board[i]
        if p == "P":
            j = i - 10
            if board[j] == ".":
                if j < 30:
                    add((i, j, "Q"))
                    add((i, j, "N"))
                    add((i, j, "R"))
                    add((i, j, "B"))
                else:
                    add((i, j, ""))
                    if i > 80 and board[j - 10] == ".":
                        add((i, j - 10, ""))
            for j in (i - 11, i - 9):
                if board[j] in ENEMY or j == ep:
                    if j < 30:
                        add((i, j, "Q"))
                        add((i, j, "N"))
                        add((i, j, "R"))
                        add((i, j, "B"))
                    else:
                        add((i, j, ""))
        elif p == "N":
            for j in KNIGHT_TGT[i]:
                if board[j] in EMPTY_OR_ENEMY:
                    add((i, j, ""))
        elif p == "K":
            for j in KING_TGT[i]:
                if board[j] in EMPTY_OR_ENEMY:
                    add((i, j, ""))
        else:
            for ray in SLIDER_RAYS[p][i]:
                for j in ray:
                    q = board[j]
                    if q == ".":
                        add((i, j, ""))
                        continue
                    if q in ENEMY:
                        add((i, j, ""))
                    break
    if wc and not in_check and (k == 95 or k == 94):
        if wc & 1 and board[A1] == "R":
            ok = True
            for x in range(A1 + 1, k):
                if board[x] != ".":
                    ok = False
                    break
            if ok and not attacked(board, k - 1):
                add((k, k - 2, ""))
        if wc & 2 and board[H1] == "R":
            ok = True
            for x in range(k + 1, H1):
                if board[x] != ".":
                    ok = False
                    break
            if ok and not attacked(board, k + 1):
                add((k, k + 2, ""))
    return moves


def gen_captures(board, ep):
    """Captures and queen promotions (for quiescence search)."""
    moves = []
    add = moves.append
    for mo in OWN_RE.finditer(board):
        i = mo.start()
        p = board[i]
        if p == "P":
            if i < 40 and board[i - 10] == ".":
                add((i, i - 10, "Q"))
            for j in (i - 11, i - 9):
                if board[j] in ENEMY or j == ep:
                    add((i, j, "Q" if j < 30 else ""))
        elif p == "N":
            for j in KNIGHT_TGT[i]:
                if board[j] in ENEMY:
                    add((i, j, ""))
        elif p == "K":
            for j in KING_TGT[i]:
                if board[j] in ENEMY:
                    add((i, j, ""))
        else:
            for ray in SLIDER_RAYS[p][i]:
                for j in ray:
                    q = board[j]
                    if q != ".":
                        if q in ENEMY:
                            add((i, j, ""))
                        break
    return moves


def make_move(pos, m, k, need_check, pst):
    """Return the child position (rotated), or None if the move is illegal."""
    board, wc, bc, ep, score = pos
    i, j, pr = m
    p = board[i]
    q = board[j]
    t = pst[p]
    v = t[j] - t[i]
    if q != ".":
        v += pst[q.upper()][119 - j]
    if i < j:
        nb = board[:i] + "." + board[i + 1:j] + p + board[j + 1:]
    else:
        nb = board[:j] + p + board[j + 1:i] + "." + board[i + 1:]
    nep = 0
    if p == "P":
        if pr:
            v += pst[pr][j] - t[j]
            nb = nb[:j] + pr + nb[j + 1:]
        elif j == ep:
            nb = nb[:j + 10] + "." + nb[j + 11:]
            v += pst["P"][119 - (j + 10)]
        elif i - j == 20 and (board[j - 1] == "p" or board[j + 1] == "p"):
            nep = i - 10
    elif p == "K":
        wc = 0
        if j - i == 2:
            nb = nb[:i + 1] + "R" + nb[i + 2:H1] + "." + nb[H1 + 1:]
            v += pst["R"][i + 1] - pst["R"][H1]
        elif i - j == 2:
            nb = nb[:A1] + "." + nb[A1 + 1:i - 1] + "R" + nb[i:]
            v += pst["R"][i - 1] - pst["R"][A1]
    if wc:
        if i == A1:
            wc &= 2
        elif i == H1:
            wc &= 1
    if bc:
        if j == A8:
            bc &= 1
        elif j == H8:
            bc &= 2
    if need_check and attacked(nb, j if p == "K" else k):
        return None
    return (nb[::-1].swapcase(), bc, wc, 119 - nep if nep else 0, -(score + v))


def pos_from_chess(cb, pst):
    """Convert a python-chess Board into the rotated mailbox position."""
    rows = [PAD_ROW, PAD_ROW]
    for rank in range(7, -1, -1):
        row = [" "]
        for f in range(8):
            piece = cb.piece_at(chess.square(f, rank))
            row.append(piece.symbol() if piece else ".")
        row.append("\n")
        rows.append("".join(row))
    rows += [PAD_ROW, PAD_ROW]
    board = "".join(rows)
    score = 0
    for i in SQUARES:
        c = board[i]
        if c.isupper():
            score += pst[c][i]
        elif c.islower():
            score -= pst[c.upper()][119 - i]
    wc = 0
    if board[95] == "K":
        if cb.has_queenside_castling_rights(chess.WHITE) and board[A1] == "R":
            wc |= 1
        if cb.has_kingside_castling_rights(chess.WHITE) and board[H1] == "R":
            wc |= 2
    bc = 0
    if board[25] == "k":
        if cb.has_kingside_castling_rights(chess.BLACK) and board[H8] == "r":
            bc |= 1
        if cb.has_queenside_castling_rights(chess.BLACK) and board[A8] == "r":
            bc |= 2
    ep = 0
    if cb.ep_square is not None and cb.has_legal_en_passant():
        ep = (9 - chess.square_rank(cb.ep_square)) * 10 + chess.square_file(cb.ep_square) + 1
    if cb.turn == chess.WHITE:
        return (board, wc, bc, ep, score)
    return (board[::-1].swapcase(), bc, wc, 119 - ep if ep else 0, -score)


def square_name(i):
    return "abcdefgh"[i % 10 - 1] + str(10 - i // 10)


def move_to_uci(m, white):
    i, j, pr = m
    if not white:
        i, j = 119 - i, 119 - j
    return square_name(i) + square_name(j) + pr.lower()


def fen_key(fen):
    """Repetition identity of a FEN: placement, side, castling, en passant."""
    return " ".join(fen.split(" ")[:4])


